import type { ChannelName } from './channels';

export type PluginSettingSpec =
  | {
      key: string;
      type: 'boolean';
      label: string;
    }
  | {
      key: string;
      type: 'number';
      label: string;
      min?: number;
      max?: number;
      step?: number;
    }
  | {
      key: string;
      type: 'select';
      label: string;
      options: readonly string[];
    }
  | {
      key: string;
      type: 'text';
      label: string;
      maxLength?: number;
    };

export interface WidgetPluginManifest {
  manifestVersion: 1;
  id: string;
  name: string;
  version: string;
  apiVersion: 1;
  entry: string;
  styles?: readonly string[];
  widget: {
    name: string;
    defaultLayout: { width: number; height: number };
    defaultConfig: Record<string, unknown>;
    settings: readonly PluginSettingSpec[];
  };
  requires: {
    channels: readonly ChannelName[];
  };
}

/** Renderer URLs generated by main from validated package-relative paths. */
export interface InstalledWidgetPlugin {
  manifest: WidgetPluginManifest;
  entryUrl: string;
  styleUrls: readonly string[];
}

const PLUGIN_ID_PATTERN =
  /^[a-z0-9]+(?:-[a-z0-9]+)*(?:\.[a-z0-9]+(?:-[a-z0-9]+)*)+$/;

/** Derives the UMD export name from a validated namespaced plugin ID. */
export const getPluginGlobalExport = (id: string): string => {
  if (id.length > 128 || !PLUGIN_ID_PATTERN.test(id)) {
    throw new Error(`Invalid widget plugin ID: ${id}`);
  }
  return `IrdashiesPlugin_${id
    .replace(/\./g, '$dot$')
    .replace(/-/g, '$dash$')}`;
};

/** Window property containing the host React and JSX runtime for plugin UMDs. */
export const WIDGET_PLUGIN_HOST_GLOBAL = '__IRDASHIES_PLUGIN_HOST__';

export interface PluginWidgetProps<
  Config extends object = Record<string, unknown>,
  Snapshots extends object = Record<string, unknown>,
> {
  widgetId: string;
  config: Readonly<Config>;
  snapshots: Readonly<Snapshots>;
  theme: Readonly<Record<string, string>>;
  preview: boolean;
  onConfigChange(patch: Partial<Config>): void;
}

export interface WidgetPluginBridge {
  getInstalledPlugins(): Promise<InstalledWidgetPlugin[]>;
}

